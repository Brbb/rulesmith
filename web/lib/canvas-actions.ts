import { isRouter } from "./routing";
import type { Policy, Stage } from "./types";
export const terminalOutcomes = ["PASS", "REJECT", "FLAG", "UNKNOWN"] as const;
export const resultOutcomes = [...terminalOutcomes, "EXECUTION_ERROR"] as const;
export function makeStage(
  kind: Stage["kind"],
  id: string,
  outcome = "PASS",
): Stage {
  if (kind === "decision")
    return {
      id,
      name:
        outcome === "REJECT"
          ? "Reject"
          : outcome === "FLAG"
            ? "Review"
            : outcome === "UNKNOWN"
              ? "Unknown"
              : "Approve",
      kind,
      outcome,
      explanation: "",
    };
  if (kind === "if" || kind === "switch")
    return {
      id,
      name: kind === "if" ? "IF" : "Switch",
      kind,
      explanation: "",
      cases: [
        {
          id: `${id}_true`,
          label: kind === "if" ? "True" : "Matching case",
          condition: "false",
          order: 1,
        },
        {
          id: `${id}_false`,
          label: kind === "if" ? "False" : "Otherwise",
          default: true,
          order: 2,
        },
      ],
    };
  return {
    id,
    name: kind === "javascript" ? "Code" : "Evaluation",
    kind,
    explanation: "",
    outputs: {
      value: {
        type: kind === "javascript" ? "number" : "boolean",
        required: true,
      },
    },
    ...(kind === "javascript"
      ? { script: "return { value: Number(input.value ?? 0) };" }
      : { expressions: { value: "true" } }),
  };
}
/** The dedicated append connector is separate from stable case/edge identities. */
export function newBranchHandle(stage: Stage): string {
  let id = `${stage.id}:add-branch`;
  while (stage.cases?.some((item) => item.id === id)) id += "_";
  return id;
}
export function connectStages(
  policy: Policy,
  sourceId: string,
  targetId: string,
  sourceHandle?: string | null,
  intent: "add" | "replace" = "add",
): Policy {
  const source = policy.stages.find((stage) => stage.id === sourceId);
  if (!source || !policy.stages.some((stage) => stage.id === targetId))
    throw new Error("The source or destination no longer exists.");
  if (source.kind === "decision")
    throw new Error("Decisions end the workflow.");
  const router = isRouter(source);
  const appendHandle =
    source.kind === "switch" && sourceHandle === newBranchHandle(source);
  if (
    router &&
    !appendHandle &&
    !source.cases?.some((item) => item.id === sourceHandle)
  )
    throw new Error("Use a case connector on the routing block.");
  let previous = policy.edges.find(
    (edge) => edge.from === sourceId && (!router || edge.id === sourceHandle),
  );
  if (
    source.kind === "if" &&
    intent === "add" &&
    previous &&
    previous.to !== targetId
  )
    throw new Error(
      "IF already has this path. Change its destination in the case editor, or use a Switch for more branches.",
    );
  if (
    source.kind === "switch" &&
    (appendHandle || (intent === "add" && previous))
  ) {
    const id = `case_${crypto.randomUUID().slice(0, 8)}`;
    const cases = source.cases || [];
    const order =
      Math.max(
        0,
        ...cases.filter((item) => !item.default).map((item) => item.order || 0),
      ) + 1;
    policy = {
      ...policy,
      stages: policy.stages.map((stage) =>
        stage.id === sourceId
          ? {
              ...stage,
              cases: [
                ...cases,
                {
                  id,
                  label: `New case ${cases.filter((item) => !item.default).length + 1}`,
                  condition: "false",
                  order,
                },
              ],
            }
          : stage,
      ),
    };
    sourceHandle = id;
    previous = undefined;
  }
  if (!router && previous && previous.to !== targetId)
    throw new Error(
      "This block already has a next step. Add IF or Switch to choose between paths.",
    );
  const queue = [targetId],
    seen = new Set<string>();
  while (queue.length) {
    const id = queue.pop()!;
    if (id === sourceId)
      throw new Error("This connection would create a cycle.");
    if (seen.has(id)) continue;
    seen.add(id);
    queue.push(
      ...policy.edges
        .filter((edge) => edge.from === id && edge.id !== previous?.id)
        .map((edge) => edge.to),
    );
  }
  const id = router
    ? sourceHandle!
    : previous?.id || `edge_${crypto.randomUUID().slice(0, 8)}`;
  const edges = [
    ...policy.edges.filter((edge) => edge.id !== id),
    { id, from: sourceId, to: targetId },
  ];
  // Dispose only of unused placeholder decisions generated by the editor itself.
  const orphan =
    previous?.to !== targetId &&
    previous &&
    (previous.to.startsWith("decision_") ||
      previous.to === `${sourceId}_review`) &&
    !edges.some((edge) => edge.from === previous.to || edge.to === previous.to);
  return {
    ...policy,
    edges,
    stages: orphan
      ? policy.stages.filter(
          (stage) => stage.id !== previous?.to || stage.kind !== "decision",
        )
      : policy.stages,
  };
}
export function addConnectedStage(
  policy: Policy,
  sourceId: string,
  sourceHandle: string | null,
  kind: Stage["kind"],
  outcome = "PASS",
) {
  const stage = makeStage(
    kind,
    `stage_${crypto.randomUUID().slice(0, 8)}`,
    outcome,
  );
  return {
    id: stage.id,
    policy: connectStages(
      { ...policy, stages: [...policy.stages, stage] },
      sourceId,
      stage.id,
      sourceHandle,
    ),
  };
}
